export function localizeError(message: string, language: Language) {
  if (language !== 'ar') return message;
  return errorMessages.find(([pattern]) => pattern.test(message))?.[1] || 'تعذر إكمال العملية. راجع البيانات وحاول مرة أخرى.';
}
