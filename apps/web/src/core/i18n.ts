export function localizeError(message: string, language: Language) {
  if (language !== "ar") return message;
  if (ar[message]) return ar[message];
  const required=message.match(/^(.+) is required and must be at most (\d+) characters$/);
  if(required)return `${t(required[1],language)} مطلوب، بحد أقصى ${required[2]} حرفاً.`;
  const transition=message.match(/^Cannot change (\w+) from (\w+) to (\w+)$/);
  if(transition)return `لا يمكن تغيير ${t(transition[1],language)} من «${t(transition[2],language)}» إلى «${t(transition[3],language)}». اختر إجراءً من الانتقالات المتاحة.`;
  return (
    errorMessages.find(([pattern]) => pattern.test(message))?.[1] ||
    "تعذر إكمال العملية. راجع البيانات وحاول مرة أخرى."
  );
}
