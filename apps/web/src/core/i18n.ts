const translate = (value: string, language: Language): string => {
  if (!value) return value;
  if (language === "en") { const english = englishByArabic.get(value) ?? value; return plainEnglish[english] ?? englishEnums[english] ?? english; }
  if (ar[value]) return ar[value];
  const av8Event=value.replace(/^AV8_/,'').match(/^(DOCUMENT|ENGLISH|VISA|TRAVEL|TASK|EXCEPTION|CONTACT|ASSIGNMENT|PROGRESS)_(.+)$/);
  if(av8Event)return `${t(({DOCUMENT:'Document',ENGLISH:'English',VISA:'Visa',TRAVEL:'Travel',TASK:'Task',EXCEPTION:'Request exception',CONTACT:'Student details',ASSIGNMENT:'Responsible staff',PROGRESS:'Progress'} as Record<string,string>)[av8Event[1]],language)}: ${t(av8Event[2],language)}`;
  const av8Prefix = value.match(/^(Document|Student payment|Academy transfer): (.+)$/);
  if(av8Prefix){const parts=av8Prefix[2].match(/^(.*?)( \(USD .*\))?$/)!;return `${({Document:'مستند','Student payment':'دفعة الطالب','Academy transfer':'تحويل الأكاديمية'} as Record<string,string>)[av8Prefix[1]]}: ${t(parts[1],language)}${parts[2]||''}`;}
  if(/^Deferred installment \d+$/.test(value)) return value.replace('Deferred installment','القسط المؤجل');

  const permissionDescription = value.match(
    /^(View records|Create records|Edit records|Delete records|Approve records|Reject records|Cancel records|Print records|Export records|Import records|Post to accounting|Reopen records|View record history|Convert records|Process records|Reconcile records|Manage configuration|Use module) in (.+)$/i,
  );
  if (permissionDescription)
    return `${t(permissionDescription[1].toLowerCase().replace(" records", "").replace(" record history", "").replace(" to accounting", "").replace(" configuration", "").replace(" module", ""), language)} ${t(permissionDescription[2].replaceAll("_", " "), language)}`;

  let match = value.match(/^(\d+) persisted records · newest first$/);
  if (match)
    return `${arabicNumber(match[1])} من السجلات المحفوظة · الأحدث أولًا`;
  match = value.match(/^(\d+) records$/);
  if (match) return `${arabicNumber(match[1])} سجل`;
  match = value.match(/^(\d+) waiting$/);
  if (match) return `${arabicNumber(match[1])} بانتظار المراجعة`;
  match = value.match(/^(\d+) items$/);
  if (match) return `${arabicNumber(match[1])} صنف`;
  match = value.match(/^No (.+) records$/);
  if (match) {
    const normalized = match[1]
      .replaceAll("_", " ")
      .replace(/\b\w/g, (letter) => letter.toUpperCase());
    return `لا توجد سجلات ${t(normalized, language)}`;
  }
  match = value.match(/^New (.+)$/);
  if (match) return `${t(match[1], language)} جديد`;
  match = value.match(/^Create (.+)$/i);
  if (match) return `إنشاء ${t(match[1], language)}`;
  match = value.match(/^Convert to (.+)$/);
  if (match) return `تحويل إلى ${t(match[1], language)}`;
  match = value.match(/^Convert (.+) to (.+)$/);
  if (match) return `تحويل ${match[1]} إلى ${t(match[2], language)}`;
  match = value.match(/^Convert (.+) quantity$/);
  if (match) return `كمية تحويل ${match[1]}`;
  match = value.match(/^(.+) comment$/);
  if (match) return `تعليق ${t(match[1], language)}`;
  match = value.match(/^(.+) · debit equals credit$/);
  if (match) return `${match[1]} · إجمالي المدين يساوي إجمالي الدائن`;
  match = value.match(/^(.+) open · expected (.+)$/);
  if (match) return `${match[1]} مفتوحة · المتوقع ${match[2]}`;
  match = value.match(/^(.+) each$/);
  if (match) return `${match[1]} للوحدة`;
  match = value.match(/^(.+) · outstanding (.+)$/);
  if (match) return `${match[1]} · المتبقي ${match[2]}`;
  match = value.match(/^Statement difference (.+) · unmatched (.+)$/);
  if (match) return `فرق كشف الحساب ${match[1]} · غير مطابق ${match[2]}`;
  match = value.match(/^(Bill|Receipt|Invoice|Delivery) (.+)$/);
  if (match) return `${t(match[1], language)} ${match[2]}`;
  match = value.match(
    /^(Customer receivable|Sales revenue|Output VAT|Supplier payable|Input VAT|Inventory issue|Inventory receipt|Inventory return|Returned inventory|COGS reversal|COGS|Revenue|Reverse GRNI|Inventory gain|Inventory loss) (.+)$/,
  );
  if (match) return `${t(match[1], language)} ${match[2]}`;
  match = value.match(/^Edit (.+) description$/);
  if (match) return `تعديل بيان ${match[1]}`;
  match = value.match(/^Reverses entry #(.+)$/);
  if (match) return `يعكس القيد رقم ${match[1]}`;
  match = value.match(/^(.+) · (.+) created$/);
  if (match) return `تم إنشاء ${match[1]} · ${t(match[2], language)}`;
  match = value.match(/^(.+) saved as draft$/);
  if (match) return `تم حفظ ${match[1]} كمسودة`;
  match = value.match(/^(.+): ([a-z/]+) completed(?: · (.+))?$/i);
  if (match) {
    const action = match[2].split("/")[0].toUpperCase();
    return `${match[1]}: اكتمل إجراء ${t(action, language)}${match[3] ? ` · ${t(match[3], language)}` : ""}`;
  }
  match = value.match(/^(Document|Journal) (approved|rejected)$/);
  if (match)
    return match[2] === "approved"
      ? `تم اعتماد ${t(match[1], language)}`
      : `تم رفض ${t(match[1], language)}`;
  match = value.match(/^(.+) draft updated$/);
  if (match) return `تم تحديث مسودة ${match[1]}`;
  match = value.match(/^(.+) is now (closed|open)$/);
  if (match)
    return `${match[1]} أصبحت ${match[2] === "closed" ? "مغلقة" : "مفتوحة"}`;
  match = value.match(/^(.+) created and balanced$/);
  if (match) return `تم إنشاء ${match[1]} والتحقق من توازنه`;
  match = value.match(/^(.+) created open$/);
  if (match) return `تم إنشاء ${match[1]} بحالة مفتوحة`;
  match = value.match(/^(.+) posted, allocated, and journaled$/);
  if (match) return `تم ترحيل ${match[1]} وتخصيصه وإنشاء قيده`;
  match = value.match(/^Shift (.+) opened with counted cash$/);
  if (match) return `تم فتح الوردية ${match[1]} برصيد نقدي فعلي`;
  match = value.match(/^(.+) held for resume$/);
  if (match) return `تم تعليق ${match[1]} لاستكمالها لاحقًا`;
  match = value.match(/^(.+) completed with stock and journal effects$/);
  if (match) return `اكتملت ${match[1]} مع ترحيل آثار المخزون والقيد`;
  match = value.match(/^Shift closed · difference (.+)$/);
  if (match) return `تم إغلاق الوردية · الفرق ${match[1]}`;
  match = value.match(/^(.+) resumed and completed$/);
  if (match) return `تم استكمال ${match[1]} وإتمامها`;
  match = value.match(/^(.+) returned with stock and journal reversal$/);
  if (match) return `تم تسجيل مرتجع ${match[1]} وعكس آثار المخزون والقيد`;
  if (value === "Statement line reconciled")
    return "تمت مطابقة حركة كشف الحساب";
  match = value.match(/^(.+) posted with journal (.+)$/);
  if (match) return `تم ترحيل ${match[1]} بالقيد ${match[2]}`;
  if (value === "Bank statement line imported and awaiting match")
    return "تم استيراد حركة كشف الحساب وهي بانتظار المطابقة";
  match = value.match(/^(.+) (CSV|PDF) exported$/);
  if (match) return `تم تصدير ${t(match[1], language)} بصيغة ${match[2]}`;
  match = value.match(/^No screen is configured for (.+)\.$/);
  if (match) return `لا توجد شاشة مهيأة للوحدة ${t(match[1], language)}.`;
  return value;
};

