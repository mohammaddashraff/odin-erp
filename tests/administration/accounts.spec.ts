import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
if (process.env.AV8_ENV !== 'test' || !process.env.DATABASE_URL?.includes(':5549/av8_test'))
    throw Error('Verified isolated test environment required');
const fixture = JSON.parse(readFileSync(resolve('.av8/administration-preview.json'), 'utf8'));
const output = '/tmp/av8-administration-qa';
mkdirSync(output, { recursive: true });
async function login(page: Page, email = fixture.adminEmail, password = fixture.password, path = '/admin/overview') {
    await page.context().addCookies([{ name: 'av8_language', value: 'en', url: 'http://127.0.0.1:8180' }]);
    await page.goto(path);
    await page.getByTestId('login-email').fill(email);
    await page.getByTestId('login-password').fill(password);
    await page.getByTestId('login-submit').click();
}
async function verify(page: Page, password = fixture.password) { const dialog = page.getByRole('dialog', { name: 'Verify your identity' }); await expect(dialog).toBeVisible(); await dialog.getByLabel('Password', { exact: true }).fill(password); await dialog.getByRole('button', { name: 'Verify', exact: true }).click(); await expect(dialog).toHaveCount(0); }
async function screen(page: Page, name: string) { await expect(page.locator('main h1')).toBeVisible(); await expect(page.getByText('Application error: a client-side exception has occurred')).toHaveCount(0); await page.screenshot({ path: `${output}/${name}.png`, fullPage: true }); }
