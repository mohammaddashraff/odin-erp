test('currency authority uses configured precision and keyboard-accessible inputs', async ({ page }) => {
    await login(page);
    await expect(page.getByRole('heading', { name: 'Administration Overview', exact: true })).toBeVisible();
    await page.goto('/settings/access/limits');
    await expect(page.getByRole('heading', { name: 'Company financial authority', exact: true })).toBeVisible();
    const existing = await page.getByText('1.234 KWD', { exact: true }).count();
    await page.getByRole('button', { name: 'Add authority limit', exact: true }).click();
    await page.getByLabel(/Company/).selectOption({ index: 1 });
    await page.getByLabel(/Currency/, { exact: false }).selectOption('KWD');
    await page.getByLabel(/Amount/).fill('1.234');
    await page.keyboard.press('Tab');
    await expect(page.getByLabel(/Reason/)).toBeFocused();
    await page.getByLabel(/Reason/).fill('Browser precision verification');
    await page.getByRole('button', { name: 'Save authority limit', exact: true }).click();
    await verify(page);
    await expect(page.getByText('1.234 KWD', { exact: true })).toHaveCount(existing + 1);
    await page.reload();
    await expect(page.getByText('1.234 KWD', { exact: true })).toHaveCount(existing + 1);
    await screen(page, 'company-limits-en');
});
test('create → profile → temporary sign-in → change password → self edit and reload', async ({ page, browser }) => {
    const name = `Hana QA ${Date.now()}`, email = `hana-${Date.now()}@administration.test`, temporary = 'Browser-Temporary-2026!', permanent = 'Browser-Permanent-2026!';
    await login(page);
    await expect(page.locator('.context-bar')).toBeVisible();
    await page.goto('/settings/access/users/new');
    await page.getByLabel(/Full name/).fill(name);
    await page.getByLabel(/Sign-in email/).fill(email);
    await page.getByLabel(/Access group/).selectOption(fixture.roleId);
    await page.getByLabel(/Home and permitted branch/).selectOption(fixture.branchId);
    await page.getByLabel('Phone', { exact: true }).fill('+201222222222');
    await page.getByLabel('Job title', { exact: true }).fill('Admissions coordinator');
    await page.getByLabel(/Temporary password/).fill(temporary);
    await screen(page, 'create-user-en');
    await page.getByRole('button', { name: 'Create user', exact: true }).click();
    await verify(page);
    await expect(page).toHaveURL(/\/settings\/access\/users\/\d+/);
    await expect(page.getByRole('heading', { name, exact: true }).first()).toBeVisible();
    const userPath = new URL(page.url()).pathname;
    await page.getByRole('button', { name: 'Edit details', exact: true }).click();
    await page.getByLabel('Job title', { exact: true }).fill('Senior admissions coordinator');
    await page.getByRole('button', { name: 'Save details', exact: true }).click();
    await expect(page.getByText('Senior admissions coordinator', { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByText('Senior admissions coordinator', { exact: true })).toBeVisible();
    const context = await browser.newContext();
    const person = await context.newPage();
    await login(person, email, temporary, '/my-profile');
    await expect(person.getByRole('heading', { name: 'Choose your own password' })).toBeVisible();
    await person.getByLabel(/Temporary password/).fill(temporary);
    await person.getByLabel(/New password/).fill(permanent);
    await person.getByLabel(/Confirm new password/).fill(permanent);
    await person.getByRole('button', { name: 'Change password', exact: true }).click();
    await verify(person, temporary);
    await expect(person.getByText('Password changed. Sign in again with your new password.')).toBeVisible();
    await person.getByRole('button', { name: 'Return to sign-in' }).click();
    await person.getByTestId('login-email').fill(email);
    await person.getByTestId('login-password').fill(permanent);
    await person.getByTestId('login-submit').click();
    await expect(person.getByRole('heading', { name: 'My Profile', exact: true })).toBeVisible();
    await person.getByRole('button', { name: 'Edit details', exact: true }).click();
    await person.getByLabel('Phone', { exact: true }).fill('+201333333333');
    await person.getByRole('button', { name: 'Save details', exact: true }).click();
    await expect(person.getByText('+201333333333', { exact: true })).toBeVisible();
    await person.reload();
    await expect(person.getByText('+201333333333', { exact: true })).toBeVisible();
    await screen(person, 'my-profile-non-admin-en');
    await person.getByRole('button', { name: 'Access', exact: true }).click();
    await expect(person.getByRole('button', { name: 'Edit access', exact: true })).toHaveCount(0);
    await expect(person.getByRole('heading', { name: 'Effective access' })).toBeVisible();
    await person.goto('/settings/access/users');
    await expect(person.getByRole('heading', { name: 'Access Denied', exact: true })).toBeVisible();
    await context.close();
    await page.goto(userPath);
    await page.getByRole('button', { name: 'Account & Security', exact: true }).click();
    await page.getByRole('button', { name: 'Deactivate account', exact: true }).click();
    const confirmation = page.getByRole('dialog');
    await expect(confirmation.getByLabel('Reason')).toHaveCount(0);
    await confirmation.getByRole('button', { name: 'Confirm', exact: true }).click();
    await verify(page);
    await expect(page.getByText('Inactive', { exact: true }).last()).toBeVisible();
});
